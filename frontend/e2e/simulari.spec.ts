import { test, expect } from '@playwright/test'
import { intraRapid } from './ajutor'

test('simulare cronometrată cu răspunsuri salvate și notificări opționale', async ({ page, request }) => {
  const headers = { 'X-MarkAi': '1' }
  expect((await request.post('/api/autentificare', { headers, data: { identificator: 'admin', parola: 'Test-demo-2026!' } })).ok()).toBeTruthy()
  const l = await (await request.post('/api/parcursuri', { headers, data: { materieId: 1, titlu: `Simulare ${Date.now()}`, clasa: 'Bac', vizibilitate: 'public', organizatieId: null } })).json()
  for (let i = 0; i < 5; i++) expect((await request.post(`/api/parcursuri/${l.id}/intrebari`, { headers, data: { text: `Întrebarea simulării ${i}`, activa: true, explicatie: 'Explicație numai la final.', variante: [{ text: 'Răspuns corect', corecta: true }, { text: 'Alt răspuns', corecta: false }] } })).ok()).toBeTruthy()
  await intraRapid(page, 'george')
  await page.goto('/simulari')
  await page.getByRole('combobox', { name: 'Materie', exact: true }).selectOption('1')
  await page.getByLabel('Număr de întrebări').fill('5')
  await page.getByLabel('Durata în minute').fill('5')
  await page.getByRole('button', { name: 'Începe simularea' }).click()
  await expect(page.getByRole('timer')).toBeVisible()
  await page.getByRole('button', { name: 'Răspuns corect', exact: true }).first().click()
  await expect(page.getByText('Răspuns salvat. Îl poți schimba până la final.')).toBeVisible()
  await expect(page.getByText('Explicație numai la final.')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Reia simularea' }).first().click()
  await expect(page.getByText('Răspuns salvat. Îl poți schimba până la final.')).toBeVisible()
  await page.getByRole('button', { name: 'Încheie simularea' }).click()
  await expect(page.getByText(/Nota orientativă:/)).toBeVisible()
  await page.goto('/setari')
  await page.getByRole('button', { name: 'Notificări', exact: true }).click()
  const sedinte = page.getByRole('checkbox', { name: /Ședințe/ })
  await expect(sedinte).not.toBeChecked()
  await sedinte.check()
  await page.getByRole('button', { name: 'Salvează notificările' }).click()
  await expect(page.getByText('Preferințele au fost salvate.')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Notificări', exact: true }).click()
  await expect(sedinte).toBeChecked()
})
